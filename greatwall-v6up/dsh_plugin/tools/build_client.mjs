#!/usr/bin/env node
/**
 * 零第三方依赖前端构建脚本（裁决 6）：
 * 将模块化源码 `dsh_plugin/client_src/` 按确定性顺序合成为 DSH RC5 兼容单文件 `dsh_plugin/lib/client.js`。
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const PLUGIN_ROOT = path.resolve(__dirname, '..')
const SRC_ROOT = path.join(PLUGIN_ROOT, 'client_src')
const OUT_FILE = path.join(PLUGIN_ROOT, 'lib', 'client.js')

const MODULES_ORDER = [
  'styles.js',
  'api.js',
  'components/ThreeQuestionsView.js',
  'components/LivingSurveyView.js',
  'components/BranchDetailDrawer.js',
  'index.js',
]

const chunks = []
for (const rel of MODULES_ORDER) {
  const full = path.join(SRC_ROOT, rel)
  if (!fs.existsSync(full)) {
    throw new Error(`找不到前端源码模块: ${full}`)
  }
  const body = fs.readFileSync(full, 'utf8').trim()
  if (body.includes('dsh-client-ui-primitives')) {
    throw new Error(`前端红线拦截: ${rel} 严禁引用 @deepseek-ai/dsh-client-ui-primitives！`)
  }
  chunks.push(`// --- module: client_src/${rel} ---\n${body}`)
}

const indentedBody = chunks
  .join('\n\n')
  .split('\n')
  .map((line) => (line ? `\t\t${line}` : ''))
  .join('\n')

const bundle = `// AUTO-GENERATED by dsh_plugin/tools/build_client.mjs — DO NOT EDIT DIRECTLY.
window.__ModuleLoader__.load({
\tid: "dsh-greatwall-v6up",
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });

\t\tconst jsxRuntime = require("react/jsx-runtime");
\t\tconst jsx = jsxRuntime.jsx;
\t\tconst jsxs = jsxRuntime.jsxs;
\t\tconst React = require("react");

${indentedBody}

\t\texports.apply = apply;
\t\texports.inject = inject;
\t\treturn module.exports;
\t}
});
`

fs.writeFileSync(OUT_FILE, bundle, 'utf8')
console.log(`[build_client] generated ${path.relative(PLUGIN_ROOT, OUT_FILE)} (${bundle.length} bytes, ${bundle.split('\n').length} lines)`)
